#!/usr/bin/env python3
"""Copy the Access backend into the Anderson Hicks Group Supabase project.

Run it again any time (and on switchover day): it creates any missing tables,
then empties every copied table and reloads it from the .accdb in one
transaction, so the database is never half-loaded.

    python3 -I ahg-tools/import/access_import.py

Needs mdbtools and libpq (psql) from Homebrew. Reads the backend file and the
database password from ahg-tools/private/ (gitignored). Writes CSVs to a temp
folder and deletes them afterward. Prints only table names and row counts.

Names: Access CamelCase becomes snake_case (Sales.PurchasePrice ->
sales.purchase_price, SharedatTeamLevel -> sharedat_team_level). Each copied
table gets the comment 'access:<Access name>' and each column
'access:<Access column>', which is how the policies file finds them.
"""
import csv, datetime, io, os, re, subprocess, sys, tempfile, shutil, zoneinfo

HERE = os.path.dirname(os.path.abspath(__file__))
PRIVATE = os.path.join(HERE, "..", "private")
BACKEND = os.path.join(PRIVATE, "AHG DB Backend.accdb")
PSQL = "/opt/homebrew/opt/libpq/bin/psql"
CONN = "host=aws-0-us-west-1.pooler.supabase.com port=5432 user=postgres.pjfiyfljkzcvfvcrdrcj dbname=postgres sslmode=require"

SKIP = {"MSysCompactError"}
# Hidden tables behind Access multi-value fields, copied under readable names.
HIDDEN = {"f_D7A306C4E24D49748225531B9D3CCD93_Category": "ScriptsCategoryValues"}


def snake(name):
    name = HIDDEN.get(name, name)
    s = re.sub(r"[^0-9A-Za-z]+", "_", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return re.sub(r"_+", "_", s).strip("_").lower()


def q(ident):
    return '"' + ident.replace('"', '""') + '"'


def run(args, **kw):
    return subprocess.run(args, check=True, capture_output=True, **kw).stdout


def password():
    for f in ("dbpass.txt", ".dbpass"):
        p = os.path.join(PRIVATE, f)
        if os.path.exists(p):
            return open(p).read().strip()
    sys.exit("No password file in ahg-tools/private/")


def tables():
    out = run(["mdb-tables", "-1", BACKEND]).decode()
    return [t for t in out.splitlines() if t and t not in SKIP and not t.startswith("MSys")] + list(HIDDEN)


def columns(table):
    """[(access name, pg type, serial?)] in column order, plus primary key columns."""
    header = next(csv.reader(io.StringIO(run(["mdb-export", BACKEND, table]).decode("utf-8").split("\n", 1)[0])))
    ddl = run(["mdb-schema", "-T", table, BACKEND, "postgres"]).decode()
    body = ddl[ddl.index("(") + 1: ddl.index(");")]
    types = []
    for line in body.splitlines():
        m = re.match(r'\s*"(.+?)"\s+(.+?),?\s*$', line)
        if m:
            types.append(m.group(2).replace(" NOT NULL", "").strip())
    if len(types) != len(header):
        sys.exit(f"{table}: {len(header)} columns but {len(types)} types")
    pk = re.findall(r'PRIMARY KEY \((.+?)\)', ddl)
    pkcols = []
    if pk:
        lower = {h.lower(): h for h in header}
        pkcols = [lower[c.strip().strip('"')] for c in pk[0].split(",")]
    cols = []
    for name, t in zip(header, types):
        serial = t == "SERIAL"
        if serial:
            t = "integer"
        elif t.startswith("VARCHAR") or t == "TEXT":
            t = "text"
        elif t.startswith("NUMERIC"):
            t = "numeric"
        elif t.lower().startswith("unknown"):
            t = "integer"  # multi-value field: key into its hidden table
        cols.append((name, t.lower(), serial))
    return cols, pkcols


def relationships():
    out = run(["mdb-export", BACKEND, "MSysRelationships"]).decode("utf-8", "replace")
    rels = []
    for r in csv.DictReader(io.StringIO(out)):
        enforced = not (int(r["grbit"]) & 2)
        if enforced and not r["szObject"].startswith(("MSys", "f_")):
            rels.append((r["szRelationship"], r["szObject"], r["szColumn"], r["szReferencedObject"], r["szReferencedColumn"]))
    return rels


def main():
    tmp = tempfile.mkdtemp(prefix="ahg-import-")
    try:
        names = tables()
        sql = ["\\set ON_ERROR_STOP on", "begin;"]
        info = {}
        for t in names:
            cols, pk = columns(t)
            info[t] = (cols, pk)
            st = snake(t)
            defs = []
            for name, typ, serial in cols:
                d = f"{q(snake(name))} {typ}"
                if serial:
                    d += " generated by default as identity"
                defs.append(d)
            if pk:
                defs.append("primary key (" + ", ".join(q(snake(c)) for c in pk) + ")")
            sql.append(f"create table if not exists public.{q(st)} (\n  " + ",\n  ".join(defs) + "\n);")
            sql.append(f"comment on table public.{q(st)} is {sqlstr('access:' + t)};")
            for name, _, _ in cols:
                sql.append(f"comment on column public.{q(st)}.{q(snake(name))} is {sqlstr('access:' + name)};")
            sql.append(f"alter table public.{q(st)} enable row level security;")
            sql.append(f"revoke all on public.{q(st)} from anon;")

        # Access's relationships are re-added as foreign keys at the end. On a refresh they already
        # exist and would reject rows loaded before their parent table, so drop them for the load.
        for rel, child, ccol, parent, pcol in relationships():
            if child in info and parent in info:
                sql.append(f"alter table if exists public.{q(snake(child))} drop constraint if exists {q(snake(rel)[:60] + '_fk')};")

        sql.append("truncate " + ", ".join("public." + q(snake(t)) for t in names) + ";")

        for t in names:
            cols, _ = info[t]
            path = os.path.join(tmp, snake(t) + ".csv")
            with open(path, "wb") as f:
                data = run(["mdb-export", "-H", "-D", "%Y-%m-%d", "-T", "%Y-%m-%d %H:%M:%S", "-b", "strip", BACKEND, t])
                # mdbtools prints Access's Dec 31, 1899 as day zero of 1900 (a handful of mistyped dates).
                f.write(re.sub(rb"(?<![0-9])1900-01-00(?= |,|$)", b"1899-12-31", data, flags=re.M))
            collist = ", ".join(q(snake(c[0])) for c in cols)
            sql.append(f"\\copy public.{q(snake(t))} ({collist}) from {sqlstr(path)} with (format csv)")
            for name, _, serial in cols:
                if serial:
                    st, sc = snake(t), snake(name)
                    sql.append(
                        f"select setval(pg_get_serial_sequence('public.{q(st)}', {sqlstr(sc)}), "
                        f"coalesce((select max({q(sc)}) from public.{q(st)}), 0) + 1, false);")

        for rel, child, ccol, parent, pcol in relationships():
            if child not in info or parent not in info:
                continue
            cname = snake(rel)[:60] + "_fk"
            sql.append(
                f"do $$ begin if not exists (select 1 from pg_constraint where conname = {sqlstr(cname)}) then "
                f"alter table public.{q(snake(child))} add constraint {q(cname)} foreign key ({q(snake(ccol))}) "
                f"references public.{q(snake(parent))} ({q(snake(pcol))}) not valid; end if; end $$;")

        sql.append("commit;")
        sql.append("notify pgrst, 'reload schema';")
        script = os.path.join(tmp, "load.sql")
        open(script, "w").write("\n".join(sql) + "\n")

        env = dict(os.environ, PGPASSWORD=password(), PGCLIENTENCODING="UTF8")
        r = subprocess.run([PSQL, CONN, "-q", "-f", script], env=env, capture_output=True, text=True)
        if r.returncode:
            sys.exit("Load failed, nothing was changed:\n" + r.stderr[-2000:])

        # Team members with no start date take their earliest role start (022_start_dates.sql).
        r = subprocess.run([PSQL, CONN, "-At", "-c", "select fill_start_dates()"], env=env, capture_output=True, text=True)
        print("start dates filled from role history:", (r.stdout.strip() or r.stderr.strip()))

        # Leads and sales were just replaced, so links from jots point at nothing (or the wrong rows).
        # Start the automatic step over from when this copy of Access was taken (its file time, in
        # Jotform's clock, Mountain time): jots after that create or link again.
        copy_time = datetime.datetime.fromtimestamp(os.path.getmtime(BACKEND), zoneinfo.ZoneInfo("America/Boise")).strftime("%Y-%m-%d %H:%M:%S")
        r = subprocess.run([PSQL, CONN, "-At", "-c", f"select jot_after_refresh('{copy_time}')"], env=env, capture_output=True, text=True)
        print("jots since the copy (" + copy_time + "):", (r.stdout.strip() or r.stderr.strip()))

        counts = "select " + ", ".join(
            f"(select count(*) from public.{q(snake(t))})" for t in names)
        out = subprocess.run([PSQL, CONN, "-At", "-F", "\t", "-c", counts], env=env,
                             capture_output=True, text=True, check=True).stdout.strip().split("\t")
        for t, n in zip(names, out):
            print(f"{int(n):>7}  {snake(t)}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def sqlstr(s):
    return "'" + s.replace("'", "''") + "'"


if __name__ == "__main__":
    main()
